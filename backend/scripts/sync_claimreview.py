"""Load Google's public ClaimReview feed into Postgres (`claimreview_index`) and embed a priority subset.

    cd backend && $PY scripts/sync_claimreview.py                 # parse local copy, upsert, embed
    cd backend && $PY scripts/sync_claimreview.py --refresh       # re-download the feed first (ETag aware)
    cd backend && $PY scripts/sync_claimreview.py --embed-cap 0   # upsert only

D-15 keyless substitute for the Google Fact Check API. The feed lives at
VERILOOP_HOME/datasets/claimreview/data.json (~200 MB, refreshed daily upstream). Parsing streams one
element at a time (see services/evidence/feed_parse.py); rows are bulk-upserted with
`repo.upsert_claimreviews` (the FTS tsvector is generated by Postgres). Embeddings (multilingual-e5,
`passage:` prefix) are computed for a prioritised subset — India-related reviews and the last ~3
years first — because the query side reranks FTS candidates by embedding and embeds misses on the fly.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path

import httpx
import structlog

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from veriloop.core.config import Settings, get_settings  # noqa: E402
from veriloop.core.logging import configure_logging  # noqa: E402
from veriloop.core.ml import Embedder  # noqa: E402
from veriloop.db import repo  # noqa: E402
from veriloop.db.engine import Database  # noqa: E402
from veriloop.services.evidence.feed_parse import iter_feed_elements, parse_element  # noqa: E402
from veriloop.services.evidence.lists import load_lists, registrable_domain  # noqa: E402

log = structlog.get_logger("sync_claimreview")

FEED_URL = "https://storage.googleapis.com/datacommons-feeds/claimreview/latest/data.json"
EMBED_TEXT_CHARS = 512  # e5 truncates at 512 tokens; long claims only slow the encoder down

# India-related publishers seen in the feed (research.md) beyond the factcheckers list.
_INDIA_EXTRA = {"youturn.in", "factcrescendo.com", "thip.media", "amarujala.com", "newsmeter.in", "dfrac.org"}


def feed_path(settings: Settings) -> Path:
    return settings.home / "datasets" / "claimreview" / "data.json"


async def download(settings: Settings, dest: Path) -> dict[str, object]:
    """Conditional GET (ETag) streamed to a temp file on VERILOOP_HOME (never C:/%TEMP%)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    etag_file = dest.with_suffix(".etag")
    headers = {}
    if await asyncio.to_thread(lambda: dest.exists() and etag_file.exists()):
        headers["If-None-Match"] = etag_file.read_text(encoding="utf-8").strip()
    tmp = dest.with_suffix(".json.part")
    started = time.perf_counter()
    async with (
        httpx.AsyncClient(timeout=httpx.Timeout(60, connect=10), follow_redirects=True) as client,
        client.stream("GET", FEED_URL, headers=headers) as resp,
    ):
        if resp.status_code == 304:
            log.info("feed_not_modified", path=str(dest))
            return {"status": 304}
        resp.raise_for_status()
        size = 0
        with tmp.open("wb") as fh:
            async for chunk in resp.aiter_bytes(1 << 20):
                fh.write(chunk)
                size += len(chunk)
        etag = resp.headers.get("etag")
        last_modified = resp.headers.get("last-modified")
    tmp.replace(dest)
    if etag:
        etag_file.write_text(etag, encoding="utf-8")
    took = round(time.perf_counter() - started, 1)
    log.info("feed_downloaded", bytes=size, seconds=took, last_modified=last_modified)
    return {"status": 200, "bytes": size, "seconds": took, "last_modified": last_modified}


def india_domains() -> set[str]:
    lists = load_lists()
    out = {
        d for d, fc in lists.factcheckers.items() if fc.domain.endswith(".in") or "india" in fc.name.lower()
    }
    out |= {d for d in lists.factcheckers if d.endswith(".in")}
    out |= _INDIA_EXTRA
    return {registrable_domain(d) for d in out}


def priority(rec: repo.ClaimReviewRecord, india: set[str], recent_cutoff: datetime) -> int:
    """Lower = embedded first: India+recent, India, recent, rest."""
    site = registrable_domain(rec.publisher_site or rec.review_url)
    is_india = site in india or (rec.language in {"hi", "bn", "te", "ta", "kn", "ml", "gu", "pa"})
    is_recent = rec.review_date is not None and rec.review_date >= recent_cutoff
    return (0 if is_india else 2) + (0 if is_recent else 1)


async def upsert_feed(
    db: Database, path: Path, *, limit: int | None
) -> tuple[dict[str, int], list[tuple[int, str]]]:
    india = india_domains()
    cutoff = datetime.now(UTC) - timedelta(days=3 * 365)
    stats = {"elements": 0, "null_items": 0, "reviews": 0, "upserted": 0}
    order: list[tuple[int, str]] = []
    batch: list[repo.ClaimReviewRecord] = []

    async def flush() -> None:
        if batch:
            stats["upserted"] += await repo.upsert_claimreviews(db, batch, batch_size=5000)
            batch.clear()

    for element in iter_feed_elements(path):
        stats["elements"] += 1
        if element.get("item") is None:
            stats["null_items"] += 1
        for rec in parse_element(element):
            stats["reviews"] += 1
            order.append((priority(rec, india, cutoff), rec.id))
            batch.append(rec)
        if len(batch) >= 5000:
            await flush()
            log.info("upsert_progress", **stats)
        if limit and stats["elements"] >= limit:
            break
    await flush()
    return stats, order


async def embed_subset(
    db: Database, embedder: Embedder, order: list[tuple[int, str]], *, cap: int, batch: int
) -> dict[str, float]:
    if cap <= 0:
        return {"embedded": 0}
    # Only rows still missing a vector (re-runs are incremental; changed texts were reset by the merge).
    missing = {r["id"] for r in await db.fetch("SELECT id FROM claimreview_index WHERE embedding IS NULL")}
    ids = [rid for _, rid in sorted(order) if rid in missing]
    ids = list(dict.fromkeys(ids))[:cap]
    started = time.perf_counter()
    done = 0
    for start in range(0, len(ids), batch):
        chunk = ids[start : start + batch]
        rows = await db.fetch(
            "SELECT id, claim_text FROM claimreview_index WHERE id = ANY($1::text[])", chunk
        )
        texts = [r["claim_text"][:EMBED_TEXT_CHARS] for r in rows]
        vectors = await embedder.embed(texts, kind="passage")
        await repo.set_claimreview_embeddings(db, [(r["id"], v) for r, v in zip(rows, vectors, strict=True)])
        done += len(rows)
        if (start // batch) % 20 == 0:
            rate = done / max(1e-6, time.perf_counter() - started)
            log.info("embed_progress", done=done, total=len(ids), per_s=round(rate, 1))
    took = time.perf_counter() - started
    return {"embedded": done, "seconds": round(took, 1), "per_s": round(done / max(took, 1e-6), 1)}


async def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--file",
        type=Path,
        default=None,
        help="feed JSON (default VERILOOP_HOME/datasets/claimreview/data.json)",
    )
    ap.add_argument("--refresh", action="store_true", help="re-download the feed first")
    ap.add_argument("--embed-cap", type=int, default=40000, help="max rows to embed this run (0 = none)")
    ap.add_argument("--batch", type=int, default=128, help="embedding batch size")
    ap.add_argument("--limit", type=int, default=0, help="parse only the first N feed elements (testing)")
    ap.add_argument("--skip-upsert", action="store_true", help="only embed rows already in the index")
    args = ap.parse_args(argv)

    settings = get_settings()
    configure_logging(settings.log_level, json_logs=False)
    settings.ensure_dirs()
    path = args.file or feed_path(settings)
    summary: dict[str, object] = {"feed": str(path)}
    if args.refresh:
        summary["download"] = await download(settings, path)
    if not path.exists():
        log.error("feed_missing", path=str(path), hint="run with --refresh")
        return 2

    db = await Database.connect(settings)
    try:
        await db.apply_schema()
        started = time.perf_counter()
        if args.skip_upsert:
            rows = await db.fetch(
                "SELECT id, review_date, publisher_site, review_url, language FROM claimreview_index"
            )
            india = india_domains()
            cutoff = datetime.now(UTC) - timedelta(days=3 * 365)
            order = []
            for r in rows:
                rec = repo.ClaimReviewRecord(
                    id=r["id"],
                    claim_text="x",
                    review_url=r["review_url"],
                    publisher_site=r["publisher_site"],
                    review_date=r["review_date"],
                    language=r["language"],
                )
                order.append((priority(rec, india, cutoff), r["id"]))
        else:
            stats, order = await upsert_feed(db, path, limit=args.limit or None)
            summary["parse_upsert"] = {**stats, "seconds": round(time.perf_counter() - started, 1)}
            log.info("upsert_done", **summary["parse_upsert"])  # type: ignore[arg-type]
        summary["priority_counts"] = {
            "india_recent": sum(1 for p, _ in order if p == 0),
            "india_older": sum(1 for p, _ in order if p == 1),
            "other_recent": sum(1 for p, _ in order if p == 2),
            "other_older": sum(1 for p, _ in order if p == 3),
        }
        embedder = Embedder(settings)
        if args.embed_cap > 0 and not await embedder.load():
            log.error("embedder_unavailable", error=embedder.error)
            summary["embed"] = {"error": embedder.error}
        else:
            summary["embed"] = await embed_subset(db, embedder, order, cap=args.embed_cap, batch=args.batch)
        stats_row = await repo.claimreview_stats(db)
        summary["index"] = stats_row.model_dump(mode="json")
    finally:
        await db.close()
    print(json.dumps(summary, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
