"""extract_claims: ASR ∥ OCR ∥ visual query expansion -> one structured LLM call -> ClaimExtraction.

Timeline for a video: Whisper on the 16 kHz audio, EasyOCR on <= 4 diverse keyframes and the
luna visual description of <= 2 keyframes all start together; the claim-extraction call (effort none)
runs once speech + on-screen text are known, alongside the OCR-vs-ASR mismatch embedding. With the
LLM disabled or failing, the extractive heuristics produce the same contract (llm_used=False).
"""

from __future__ import annotations

import asyncio
import re
import time
from typing import Any

import numpy as np
import structlog
from rapidfuzz import fuzz

from veriloop.contracts import Claim, ClaimExtraction, Entity, MediaAsset, ResolvedInput, SubjectInfo
from veriloop.core.errors import LLMDisabled, MLUnavailable, ToolCallFailed
from veriloop.core.executor import run_cpu
from veriloop.deps import Deps
from veriloop.services.ingestion.imaging import to_data_url

from . import asr, heuristics, ocr
from .prompts import (
    CLAIM_SYSTEM,
    VISUAL_SYSTEM,
    ClaimExtractionOut,
    VisualOut,
    claim_user_prompt,
)

log = structlog.get_logger(__name__)

VISUAL_QUERY_PREFIX = "visual_query: "
VISUAL_SCENE_PREFIX = "visual_scene: "
VISUAL_NOTE = (
    "Visual search queries were generated by the LLM from keyframes; they are search queries, not evidence."
)
MAX_VISUAL_FRAMES = 2
_MISMATCH_HI, _MISMATCH_LO = 0.86, 0.72  # e5 cosine: related text ~0.87-0.9, unrelated ~0.71 (foundation.md)


def visual_queries(extraction: ClaimExtraction) -> list[str]:
    """The keyless reverse-image substitute (D-15): LLM-written search queries carried in `notes`."""
    return [n[len(VISUAL_QUERY_PREFIX) :] for n in extraction.notes if n.startswith(VISUAL_QUERY_PREFIX)]


# =============================================================================================
async def extract_claims(resolved: ResolvedInput, locale: str, deps: Deps) -> ClaimExtraction:
    started = time.perf_counter()
    timings: dict[str, int] = {}
    notes: list[str] = []
    try:
        result = await _extract(resolved, locale, deps, timings, notes)
    except Exception as exc:  # never raise to the orchestrator
        log.exception("extract_claims_failed", error=f"{type(exc).__name__}: {exc}")
        result = _heuristic(
            resolved.caption_text, None, None, None, resolved, [*notes, f"extraction error: {exc}"]
        )
    log.info(
        "extract_claims_done",
        claims=len(result.claims),
        worthiness=result.check_worthiness,
        language=result.language,
        llm_used=result.llm_used,
        timings_ms=timings,
        latency_ms=int((time.perf_counter() - started) * 1000),
    )
    return result


async def _timed(timings: dict[str, int], name: str, coro: Any) -> Any:
    t = time.perf_counter()
    try:
        return await coro
    finally:
        timings[name] = int((time.perf_counter() - t) * 1000)


async def _extract(
    resolved: ResolvedInput, locale: str, deps: Deps, timings: dict[str, int], notes: list[str]
) -> ClaimExtraction:
    settings = deps.settings
    images = [a for a in resolved.media if a.source != "page_capture"]
    keyframes = ocr.pick_keyframes(resolved.media) if resolved.media else []
    ocr_langs = ocr.choose_langs(resolved.caption_text, resolved.title, locale=locale)

    async def run_asr() -> asr.Transcript | None:
        if not resolved.audio_path or not settings.ml_enable:
            return None
        try:
            return await run_cpu(asr.transcribe_blocking, resolved.audio_path, settings)
        except Exception as exc:
            notes.append(f"ASR unavailable: {exc}")
            return None

    async def run_ocr() -> list[str]:
        if not keyframes or not settings.ml_enable:
            return []
        try:
            return await run_cpu(ocr.ocr_blocking, [a.path for a in keyframes], settings, ocr_langs)
        except Exception as exc:
            notes.append(f"OCR unavailable: {exc}")
            return []

    transcript, ocr_lines, visual = await asyncio.gather(
        _timed(timings, "asr", run_asr()),
        _timed(timings, "ocr", run_ocr()),
        _timed(timings, "visual_llm", _visual_queries(images, deps, notes)),
    )
    if not settings.ml_enable and (resolved.audio_path or keyframes):
        notes.append("ASR/OCR skipped (ML_ENABLE=false)")
    ocr_text = "\n".join(ocr_lines) or None
    transcript_text = transcript.text if transcript and transcript.text else None
    if transcript:
        notes.append(
            f"ASR faster-whisper/{transcript.model}: "
            f"{transcript.audio_s:.0f} s audio in {transcript.seconds:.1f} s"
        )
    if ocr_lines:
        notes.append(f"OCR EasyOCR {'+'.join(ocr_langs)} on up to {len(keyframes)} keyframe(s)")

    llm_task = _timed(
        timings,
        "claims_llm",
        _llm_claims(
            resolved, transcript_text, transcript.language if transcript else None, ocr_text, deps, notes
        ),
    )
    mismatch_task = _timed(timings, "mismatch", _mismatch(transcript, ocr_text, deps, notes))
    llm_out, mismatch = await asyncio.gather(llm_task, mismatch_task)

    if llm_out is not None:
        extraction = _from_llm(llm_out, resolved, transcript, ocr_text, notes)
    else:
        extraction = _heuristic(resolved.caption_text, transcript, ocr_text, resolved.title, resolved, notes)
    if visual is not None:
        _attach_visual(extraction, visual)
    extraction.asr_ocr_mismatch = mismatch
    extraction.notes = _dedupe(extraction.notes)
    return extraction


def _dedupe(items: list[str]) -> list[str]:
    out: list[str] = []
    for item in items:
        if item not in out:
            out.append(item)
    return out


# =============================================================================================
# LLM claim extraction
# =============================================================================================
async def _llm_claims(
    resolved: ResolvedInput,
    transcript: str | None,
    transcript_lang: str | None,
    ocr_text: str | None,
    deps: Deps,
    notes: list[str],
) -> ClaimExtractionOut | None:
    if not deps.llm.enabled:
        notes.append("LLM disabled — extractive claim split")
        return None
    if not any((resolved.caption_text, resolved.title, transcript, ocr_text)):
        return None
    user = claim_user_prompt(
        platform=resolved.platform.value,
        title=resolved.title,
        caption=resolved.caption_text,
        transcript=transcript,
        transcript_language=transcript_lang,
        ocr_text=ocr_text,
    )
    try:
        return await deps.llm.complete_json(
            task="extract_claims",
            system=CLAIM_SYSTEM,
            user=user,
            schema=ClaimExtractionOut,
            effort="none",
            max_tokens=1500,
        )
    except LLMDisabled:
        notes.append("LLM disabled — extractive claim split")
    except ToolCallFailed as exc:
        notes.append(f"LLM claim extraction failed ({exc.error.error_type}) — extractive fallback")
        log.warning("claim_llm_failed", error_type=exc.error.error_type, message=exc.error.message)
    return None


def _grounded(claim_text: str, sources: str) -> bool:
    """D-16 guard: an extracted claim must be traceable to the content (lexical overlap, any script)."""
    if not sources.strip():
        return False
    tokens = [t for t in re.findall(r"\w+", claim_text.lower()) if len(t) > 3]
    if not tokens:
        return fuzz.partial_ratio(claim_text.lower(), sources.lower()) >= 60
    present = sum(1 for t in tokens if t in sources.lower())
    return present / len(tokens) >= 0.35 or fuzz.token_set_ratio(claim_text, sources) >= 60


def _from_llm(
    out: ClaimExtractionOut,
    resolved: ResolvedInput,
    transcript: asr.Transcript | None,
    ocr_text: str | None,
    notes: list[str],
) -> ClaimExtraction:
    sources = "\n".join(
        filter(None, (resolved.title, resolved.caption_text, transcript and transcript.text, ocr_text))
    )
    claims: list[Claim] = []
    primary_id: str | None = None
    for idx, c in enumerate(out.claims[:5]):
        text = " ".join(c.text.split())
        if not text:
            continue
        if not _grounded(text, sources):
            notes.append(f"dropped ungrounded LLM claim: {text[:120]}")
            continue
        if any(fuzz.ratio(text.lower(), k.text.lower()) >= 92 for k in claims):
            continue
        claim = Claim(
            id=f"C{len(claims) + 1}",
            text=text,
            text_en=" ".join(c.text_en.split()) or None,
            entities=[Entity(name=e.name.strip(), type=e.type) for e in c.entities if e.name.strip()][:10],
            claim_type=c.claim_type,
            time_reference=c.time_reference or None,
            location=c.location or None,
        )
        claims.append(claim)
        if idx == out.primary_index:
            primary_id = claim.id
    language = (out.language or "").strip().lower()[:2]
    if not re.fullmatch(r"[a-z]{2}", language):
        language = heuristics.detect_language(claims[0].text if claims else resolved.caption_text)
    worthiness = float(np.clip(out.check_worthiness, 0.0, 1.0)) if claims else 0.0
    subject = SubjectInfo(
        is_identifiable_individual=out.subject.is_identifiable_individual,
        is_private_individual=out.subject.is_private_individual
        if out.subject.is_identifiable_individual
        else None,
        name=(out.subject.name or "").strip() or None,
    )
    return ClaimExtraction(
        caption_text=resolved.caption_text,
        transcript=transcript.text if transcript and transcript.text else None,
        transcript_language=transcript.language if transcript else None,
        ocr_text=ocr_text,
        language=language,
        claims=claims,
        primary_claim_id=primary_id or (claims[0].id if claims else None),
        check_worthiness=round(worthiness, 3),
        worthiness_reason=out.worthiness_reason.strip()[:300] or ("no claims found" if not claims else ""),
        subject=subject,
        llm_used=True,
        notes=notes,
    )


# =============================================================================================
# extractive fallback (D-01b)
# =============================================================================================
def _heuristic(
    caption: str | None,
    transcript: asr.Transcript | None,
    ocr_text: str | None,
    title: str | None,
    resolved: ResolvedInput,
    notes: list[str],
) -> ClaimExtraction:
    transcript_text = transcript.text if transcript and transcript.text else None
    pool: list[str] = []
    for source in (caption, title, transcript_text, ocr_text):
        for sent in heuristics.split_sentences(source):
            if sent not in pool:
                pool.append(sent)
    scored = sorted((heuristics.score_sentence(s) for s in pool), key=lambda s: -s.score)
    all_text = " ".join(filter(None, (caption, title, transcript_text, ocr_text)))
    reason = heuristics.non_claim_reason(all_text)
    picked = [s for s in scored if s.score >= 0.3][:3]
    claims: list[Claim] = []
    for s in picked:
        lang = heuristics.detect_language(s.text)
        claims.append(
            Claim(
                id=f"C{len(claims) + 1}",
                text=s.text,
                text_en=s.text if lang == "en" else None,
                entities=[Entity(name=n) for n in heuristics.extract_entities(s.text)],
                claim_type="statistic" if re.search(r"\d+(\.\d+)?\s?%", s.text) else "event",
            )
        )
    worthiness = picked[0].score if picked else (scored[0].score if scored else 0.0)
    if reason:
        worthiness = min(worthiness, 0.15)
    language = heuristics.detect_language(claims[0].text if claims else (caption or transcript_text or ""))
    if claims and language != "en":
        notes.append("Non-English claim: no translation available in extractive mode (E9)")
    person = heuristics.person_subject(all_text)
    if reason:
        why = f"Not checkable: {reason}"
    elif picked:
        why = "Extractive heuristics: " + ", ".join(r for r in picked[0].reasons if not r.startswith("-"))
    else:
        why = "No verifiable factual statement found"
    return ClaimExtraction(
        caption_text=caption,
        transcript=transcript_text,
        transcript_language=transcript.language if transcript else None,
        ocr_text=ocr_text,
        language=language,
        claims=claims,
        primary_claim_id=claims[0].id if claims else None,
        check_worthiness=round(float(worthiness), 3),
        worthiness_reason=why,
        subject=SubjectInfo(
            is_identifiable_individual=person is not None, is_private_individual=None, name=person
        ),
        llm_used=False,
        notes=notes,
    )


# =============================================================================================
# OCR vs ASR mismatch
# =============================================================================================
async def _mismatch(
    transcript: asr.Transcript | None, ocr_text: str | None, deps: Deps, notes: list[str]
) -> float | None:
    """0..1, higher = spoken words disagree with on-screen text. None when either side is too thin."""
    spoken = transcript.text if transcript else ""
    if len(spoken.split()) < 4 or not ocr_text or len(ocr_text.split()) < 4:
        return None
    if deps.embedder.available:
        try:
            vecs = await deps.embedder.embed([spoken[:2000], ocr_text[:2000]], kind="passage")
            sim = float(np.dot(vecs[0], vecs[1]))
            score = (_MISMATCH_HI - sim) / (_MISMATCH_HI - _MISMATCH_LO)
            return round(float(np.clip(score, 0.0, 1.0)), 3)
        except MLUnavailable:
            pass
    # Lexical fallback only makes sense within one language (it would flag every translation).
    if heuristics.detect_language(spoken) != heuristics.detect_language(ocr_text):
        notes.append("ASR/OCR mismatch not computed: embedder unavailable and languages differ")
        return None
    overlap = fuzz.token_set_ratio(spoken.lower(), ocr_text.lower()) / 100.0
    return round(float(np.clip(1.0 - overlap, 0.0, 1.0)), 3)


# =============================================================================================
# visual query expansion (D-15 keyless reverse-image substitute)
# =============================================================================================
async def _visual_queries(images: list[MediaAsset], deps: Deps, notes: list[str]) -> VisualOut | None:
    if not images or not deps.llm.enabled:
        return None
    frames = ocr.pick_keyframes(images, limit=MAX_VISUAL_FRAMES, min_distance=10)
    try:
        urls = [await run_cpu(to_data_url, a.path) for a in frames]
        return await deps.llm.complete_json(
            task="visual_queries",
            system=VISUAL_SYSTEM,
            user="Describe these keyframes and propose search queries.",
            schema=VisualOut,
            effort="none",
            max_tokens=700,
            images=urls,
        )
    except (LLMDisabled, ToolCallFailed, ValueError) as exc:
        why = exc.error.error_type if isinstance(exc, ToolCallFailed) else type(exc).__name__
        notes.append(f"visual query expansion unavailable: {why}")
        log.warning("visual_queries_failed", error=why, message=str(exc)[:300])
        return None


def _attach_visual(extraction: ClaimExtraction, visual: VisualOut) -> None:
    queries = []
    for q in visual.search_queries[:4]:
        q = " ".join(q.split())[:200]
        if q and q not in queries:
            queries.append(q)
    if not queries:
        return
    extraction.notes.append(VISUAL_NOTE)
    if visual.scene.strip():
        extraction.notes.append(VISUAL_SCENE_PREFIX + " ".join(visual.scene.split())[:300])
    extraction.notes.extend(VISUAL_QUERY_PREFIX + q for q in queries)
